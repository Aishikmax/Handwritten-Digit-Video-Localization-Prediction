def calculate_metrics(y_true, y_pred):
    y_true = tf.cast(y_true, tf.float32)
    y_pred = tf.cast(y_pred, tf.float32)

    # SSIM (Structural Similarity Index)
    ssim = tf.reduce_mean(tf.image.ssim(y_true, y_pred, max_val=1.0)).numpy()

