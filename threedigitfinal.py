IMG_SIZE = 64

def generate_moving_mnist_three_digits(source_images, num_sequences, num_frames):
    sequences = np.zeros((num_sequences, num_frames, IMG_SIZE, IMG_SIZE), dtype=np.float32)

    for i in range(num_sequences):
        # Buffer for current sequence
        sequence_buffer = np.zeros((num_frames, IMG_SIZE, IMG_SIZE), dtype=np.float32)

        # Pick 3 Distinct Digits
        digit_indices = np.random.choice(source_images.shape[0], 3, replace=False)

        for n in range(3):
            digit_idx = digit_indices[n]
            digit = source_images[digit_idx]

            # Augmentation
            scale = np.random.uniform(0.9, 1.1)
            digit = scipy.ndimage.zoom(digit, scale, order=1)
            angle = np.random.uniform(-15, 15)
            digit = scipy.ndimage.rotate(digit, angle, reshape=False, order=1)
            digit = np.clip(digit, 0.0, 1.0)

            d_h, d_w = digit.shape

            # Init Position & Velocity
            max_y = max(1, IMG_SIZE - d_h)
            max_x = max(1, IMG_SIZE - d_w)
            pos_y = np.random.randint(0, max_y)
            pos_x = np.random.randint(0, max_x)
            vel_y = np.random.randint(-2, 3)
            vel_x = np.random.randint(-2, 3)
            if vel_y == 0 and vel_x == 0: vel_y, vel_x = 1, 1

            for f in range(num_frames):
                # Calculate bounds
                start_y = max(0, int(pos_y)); end_y = min(IMG_SIZE, int(pos_y + d_h))
                start_x = max(0, int(pos_x)); end_x = min(IMG_SIZE, int(pos_x + d_w))

                dig_start_y = max(0, -int(pos_y))
                dig_start_x = max(0, -int(pos_x))

                # Calculate slice width/height
                h_slice = end_y - start_y
                w_slice = end_x - start_x

                if h_slice > 0 and w_slice > 0:
                    patch = digit[dig_start_y:dig_start_y+h_slice, dig_start_x:dig_start_x+w_slice]

                    # USE NP.MAXIMUM for overlaps (white stays white)
                    sequence_buffer[f, start_y:end_y, start_x:end_x] = np.maximum(
                        sequence_buffer[f, start_y:end_y, start_x:end_x],
                        patch
                    )

                # Update Position & Bounce
                pos_y += vel_y; pos_x += vel_x
                if pos_y <= 0 or pos_y >= max_y: vel_y = -vel_y
                if pos_x <= 0 or pos_x >= max_x: vel_x = -vel_x

        sequences[i] = sequence_buffer

    # Add Noise
    noise = np.random.normal(loc=0.0, scale=0.01, size=sequences.shape)
    return np.clip(sequences + noise, 0.0, 1.0)

