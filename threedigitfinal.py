class ConvGRU(layers.Layer):
    def __init__(self, filters, kernel_size, return_sequences=True, **kwargs):
        super(ConvGRU, self).__init__(**kwargs)
        self.filters = filters
        self.kernel_size = kernel_size
        self.return_sequences = return_sequences
        self.conv_z = layers.Conv2D(self.filters, self.kernel_size, padding='same', use_bias=True)
        self.conv_r = layers.Conv2D(self.filters, self.kernel_size, padding='same', use_bias=True)
        self.conv_h = layers.Conv2D(self.filters, self.kernel_size, padding='same', use_bias=True)

    def call(self, inputs):
        inputs = tf.convert_to_tensor(inputs)
        inputs_time_major = tf.unstack(inputs, axis=1)
        batch_size = tf.shape(inputs)[0]
        height, width = tf.shape(inputs)[2], tf.shape(inputs)[3]
        h_t = tf.zeros((batch_size, height, width, self.filters))
        outputs = []
        for x_t in inputs_time_major:
            concat_input = tf.concat([x_t, h_t], axis=-1)
            z_t = tf.sigmoid(self.conv_z(concat_input))
            r_t = tf.sigmoid(self.conv_r(concat_input))
            reset_h = r_t * h_t
            concat_candidate = tf.concat([x_t, reset_h], axis=-1)
            h_hat = tf.tanh(self.conv_h(concat_candidate))
            h_t = z_t * h_t + (1 - z_t) * h_hat
            outputs.append(h_t)

        if self.return_sequences: return tf.stack(outputs, axis=1)
        else: return outputs[-1]

    def compute_output_shape(self, input_shape):
        if self.return_sequences:
            return (input_shape[0], input_shape[1], input_shape[2], input_shape[3], self.filters)
        else:
            return (input_shape[0], input_shape[2], input_shape[3], self.filters)

    def get_config(self):
        config = super().get_config()
        config.update({"filters": self.filters, "kernel_size": self.kernel_size, "return_sequences": self.return_sequences})
        return config

# --- ATTENTION LAYER ---
class MultiHeadSpatiotemporalAttention(layers.Layer):
    def __init__(self, channels, num_heads=8, **kwargs):
        super(MultiHeadSpatiotemporalAttention, self).__init__(**kwargs)
        self.channels = channels
        self.num_heads = num_heads
        if channels % num_heads != 0:
            raise ValueError("Channels must be divisible by num_heads")
        self.depth = channels // num_heads

    def build(self, input_shape):
        self.query_conv = layers.Conv2D(self.channels, 1, padding='same')
        self.key_conv = layers.Conv2D(self.channels, 1, padding='same')
        self.value_conv = layers.Conv2D(self.channels, 1, padding='same')
        self.gamma = self.add_weight(name="gamma", shape=(1,), initializer="zeros", trainable=True)
        self.out_conv = layers.Conv2D(self.channels, 1, padding='same')
        super(MultiHeadSpatiotemporalAttention, self).build(input_shape)

    def call(self, inputs):
        batch_size = tf.shape(inputs)[0]
        h, w = tf.shape(inputs)[1], tf.shape(inputs)[2]

        # Projections
        query = self.query_conv(inputs)
        key = self.key_conv(inputs)
        value = self.value_conv(inputs)

        # Reshape for heads: (Batch, H*W, Heads, Depth)
        query = tf.reshape(query, (batch_size, -1, self.num_heads, self.depth))
        key = tf.reshape(key, (batch_size, -1, self.num_heads, self.depth))
        value = tf.reshape(value, (batch_size, -1, self.num_heads, self.depth))

        # Transpose for matmul: (Batch, Heads, H*W, Depth)
        query = tf.transpose(query, perm=[0, 2, 1, 3])
        key = tf.transpose(key, perm=[0, 2, 1, 3])
        value = tf.transpose(value, perm=[0, 2, 1, 3])

        # Calculate Scores
        scores = tf.matmul(query, key, transpose_b=True)
        scores = scores / tf.math.sqrt(tf.cast(self.depth, tf.float32))
        attention = tf.nn.softmax(scores, axis=-1)

        # Apply Attention to Values
        context = tf.matmul(attention, value)
        context = tf.transpose(context, perm=[0, 2, 1, 3])
        context = tf.reshape(context, (batch_size, h, w, self.channels))

        output = self.out_conv(context)
        return inputs + self.gamma * output

    def compute_output_shape(self, input_shape):
        return input_shape

    def get_config(self):
        config = super(MultiHeadSpatiotemporalAttention, self).get_config()
        config.update({"channels": self.channels, "num_heads": self.num_heads})
        return config

