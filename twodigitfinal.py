def generate_moving_mnist_two_digits(source_images, num_sequences, num_frames):
    sequences = np.zeros((num_sequences, num_frames, IMG_SIZE, IMG_SIZE), dtype=np.float32)

    for i in range(num_sequences):
        # --- Initialize State for 2 Digits ---
        digits_data = []

        for _ in range(2): # Fixed to 2 digits
            # 1. Pick and Transform Digit
            digit_idx = np.random.randint(source_images.shape[0])
            digit = source_images[digit_idx]
            angle = np.random.uniform(-15, 15)
            # reshape=False keeps the image size roughly the same (crops corners if needed)
            # reshape=True expands the image to fit the rotated digit (no cropping)
            digit = scipy.ndimage.rotate(digit, angle, reshape=False, order=1)

            scale = np.random.uniform(0.9, 1.1)
            digit = scipy.ndimage.zoom(digit, scale, order=1)
            digit = np.clip(digit, 0.0, 1.0)

            d_h, d_w = digit.shape

            # 2. Initialize Position and Velocity
            max_y, max_x = max(1, IMG_SIZE - d_h), max(1, IMG_SIZE - d_w)
            pos_y, pos_x = np.random.randint(0, max_y), np.random.randint(0, max_x)
            vel_y, vel_x = np.random.randint(-2, 3), np.random.randint(-2, 3)

            # Ensure velocity is non-zero
            if vel_y == 0 and vel_x == 0:
                vel_y, vel_x = 1, 1

            digits_data.append({
                'img': digit,
                'h': d_h, 'w': d_w,
                'pos_y': pos_y, 'pos_x': pos_x,
                'vel_y': vel_y, 'vel_x': vel_x,
                'max_y': max_y, 'max_x': max_x
            })

        # --- Generate Frames ---
        for f in range(num_frames):
            frame = np.zeros((IMG_SIZE, IMG_SIZE), dtype=np.float32)

            # Loop through both digits and draw them onto the single frame
            for d in digits_data:
                # Calculate bounding box
                start_y, end_y = max(0, int(d['pos_y'])), min(IMG_SIZE, int(d['pos_y'] + d['h']))
                start_x, end_x = max(0, int(d['pos_x'])), min(IMG_SIZE, int(d['pos_x'] + d['w']))

                dig_start_y, dig_start_x = max(0, -int(d['pos_y'])), max(0, -int(d['pos_x']))

                h_slice = end_y - start_y
                w_slice = end_x - start_x

                if h_slice > 0 and w_slice > 0:
                    # Extract the digit slice
                    digit_slice = d['img'][dig_start_y:dig_start_y+h_slice, dig_start_x:dig_start_x+w_slice]

                    # USE NP.MAXIMUM: Ensures overlapping digits blend correctly (white on white)
                    # instead of one black bounding box erasing the other digit
                    frame[start_y:end_y, start_x:end_x] = np.maximum(
                        frame[start_y:end_y, start_x:end_x],
                        digit_slice
                    )

                # Update Position
                d['pos_y'] += d['vel_y']
                d['pos_x'] += d['vel_x']

                # Update Bounce Logic
                if d['pos_y'] <= 0 or d['pos_y'] >= d['max_y']: d['vel_y'] = -d['vel_y']
                if d['pos_x'] <= 0 or d['pos_x'] >= d['max_x']: d['vel_x'] = -d['vel_x']

            sequences[i, f, :, :] = frame

    # --- ADDED GAUSSIAN NOISE ---
    # The paper specifies sigma=0.01
    noise = np.random.normal(loc=0.0, scale=0.01, size=sequences.shape)
    sequences = sequences + noise

    # Clip to ensure pixel values stay valid [0, 1]
    return np.expand_dims(np.clip(sequences, 0.0, 1.0), -1)

