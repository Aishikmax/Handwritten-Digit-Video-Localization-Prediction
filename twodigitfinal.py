class VideoGAN(tf.keras.Model):
    def __init__(self, generator, discriminator):
        super(VideoGAN, self).__init__()
        self.generator = generator
        self.discriminator = discriminator

    def compile(self, gen_opt, disc_opt, rec_loss_fn):
        super(VideoGAN, self).compile()
        self.gen_opt = gen_opt
        self.disc_opt = disc_opt
        self.rec_loss_fn = rec_loss_fn
        self.bce = tf.keras.losses.BinaryCrossentropy(from_logits=False)
        self.mse_metric = tf.keras.metrics.MeanSquaredError(name="mse")

    @property
    def metrics(self):
        return [self.mse_metric]

    def train_step(self, batch_data):
        real_input, real_target = batch_data

        with tf.GradientTape() as gen_tape, tf.GradientTape() as disc_tape:
            fake_target = self.generator(real_input, training=True)
            real_pred = self.discriminator(real_target, training=True)
            fake_pred = self.discriminator(fake_target, training=True)

            d_loss = self.bce(tf.ones_like(real_pred) * 0.9, real_pred) + self.bce(tf.zeros_like(fake_pred), fake_pred)

            g_loss_gan = self.bce(tf.ones_like(fake_pred), fake_pred)
            g_loss_l1 = self.rec_loss_fn(real_target, fake_target)
            g_loss = g_loss_gan + (100.0 * g_loss_l1)

        d_grads = disc_tape.gradient(d_loss, self.discriminator.trainable_variables)
        g_grads = gen_tape.gradient(g_loss, self.generator.trainable_variables)

        self.disc_opt.apply_gradients(zip(d_grads, self.discriminator.trainable_variables))
        self.gen_opt.apply_gradients(zip(g_grads, self.generator.trainable_variables))

        self.mse_metric.update_state(real_target, fake_target)
        return {"d_loss": d_loss, "g_loss": g_loss, "mse": self.mse_metric.result()}

# Execution
lr_schedule = tf.keras.optimizers.schedules.CosineDecayRestarts(1e-4, 1000)
gen_optimizer = tf.keras.optimizers.Adam(learning_rate=lr_schedule, beta_1=0.5)
disc_optimizer = tf.keras.optimizers.Adam(learning_rate=lr_schedule, beta_1=0.5)

def l1_loss(y_true, y_pred):
    return tf.reduce_mean(tf.abs(y_true - y_pred))

