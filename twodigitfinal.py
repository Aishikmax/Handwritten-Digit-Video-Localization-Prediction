import numpy as np
import scipy.ndimage

# constants (Ensure these are defined in your script)
IMG_SIZE = 64

def generate_moving_mnist_2digit(source_images, num_sequences, num_frames,
                                 num_digits=2, effect=None):
    """
    Generates Moving MNIST sequences with exactly `num_digits` (default 2).
    """
    # Output shape: (Batch, Frames, H, W)
    sequences = np.zeros((num_sequences, num_frames, IMG_SIZE, IMG_SIZE), dtype=np.float32)

    for i in range(num_sequences):
        # buffer for the current sequence
        sequence_buffer = np.zeros((num_frames, IMG_SIZE, IMG_SIZE), dtype=np.float32)

        # Select distinct random indices for the digits so they aren't identical
        digit_indices = np.random.choice(source_images.shape[0], num_digits, replace=False)

        for n in range(num_digits):
            digit_idx = digit_indices[n]
            digit = source_images[digit_idx]

            # --- 1. PRE-PROCESSING (Augmentation) ---
            scale = np.random.uniform(0.9, 1.1)
            digit = scipy.ndimage.zoom(digit, scale, order=1)

            if effect == 'distortion':
                angle = np.random.uniform(-30, 30)
            else:
                angle = np.random.uniform(-15, 15)

            digit = scipy.ndimage.rotate(digit, angle, reshape=False, order=1)
            digit = np.clip(digit, 0.0, 1.0)

            d_h, d_w = digit.shape

            # --- 2. INITIALIZATION (Position & Velocity) ---
            # Random position (ensure it fits within canvas)
            max_y = max(1, IMG_SIZE - d_h)
            max_x = max(1, IMG_SIZE - d_w)

            pos_y = np.random.randint(0, max_y)
            pos_x = np.random.randint(0, max_x)

            # velocity components (ensure not 0,0)
            vel_y = np.random.randint(-3, 4)
            vel_x = np.random.randint(-3, 4)
            if vel_y == 0 and vel_x == 0:
                vel_y, vel_x = 2, 2

            # --- 3. MOVEMENT LOOP ---
            for f in range(num_frames):
                # Calculate valid slices for canvas and digit
                # We determine the intersection of the digit and the canvas
                start_y = max(0, int(pos_y))
                end_y = min(IMG_SIZE, int(pos_y + d_h))
                start_x = max(0, int(pos_x))
                end_x = min(IMG_SIZE, int(pos_x + d_w))

                # Corresponding slices on the digit image
                dig_start_y = max(0, -int(pos_y))
                dig_end_y = dig_start_y + (end_y - start_y)
                dig_start_x = max(0, -int(pos_x))
                dig_end_x = dig_start_x + (end_x - start_x)

                if end_y > start_y and end_x > start_x:
                    patch = digit[dig_start_y:dig_end_y, dig_start_x:dig_end_x]

                    # KEY CHANGE: Use np.maximum instead of +=
                    # This prevents pixel values > 1.0 when white digits overlap
                    sequence_buffer[f, start_y:end_y, start_x:end_x] = np.maximum(
                        sequence_buffer[f, start_y:end_y, start_x:end_x],
                        patch
                    )

                # Physics Update (Bounce off walls)
                next_pos_y = pos_y + vel_y
                next_pos_x = pos_x + vel_x

                # Check boundaries and reflect velocity
                if next_pos_y <= 0 or next_pos_y >= max_y:
                    vel_y = -vel_y
                if next_pos_x <= 0 or next_pos_x >= max_x:
                    vel_x = -vel_x

                pos_y += vel_y
                pos_x += vel_x

        sequences[i] = sequence_buffer

    # --- 4. APPLY GLOBAL EFFECTS ---
    if effect == 'low_light':
        sequences = sequences * 0.6
    elif effect == 'motion_blur':
        # Blur across spatial dimensions (H, W) but less on time
        sequences = scipy.ndimage.gaussian_filter(sequences, sigma=(0, 0, 1.0, 1.0))
    elif effect == 'noise':
        noise = np.random.normal(loc=0.0, scale=0.15, size=sequences.shape)
        sequences = np.clip(sequences + noise, 0.0, 1.0)
    else:
        # Standard faint noise
        noise = np.random.normal(loc=0.0, scale=0.001, size=sequences.shape)
        sequences = np.clip(sequences + noise, 0.0, 1.0)

    # Return shape: (Batch, Frames, H, W, Channels=1)
    return np.expand_dims(sequences, -1)

