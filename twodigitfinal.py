def build_generator(input_frames, img_size):
    input_layer = Input(shape=(input_frames, img_size, img_size, 1))

    # --- ENCODER ---
    x = layers.TimeDistributed(layers.Conv2D(64, (3, 3), strides=1, padding='same'))(input_layer)
    x = layers.TimeDistributed(layers.LeakyReLU(0.2))(x)

    x = layers.TimeDistributed(layers.Conv2D(128, (3, 3), strides=2, padding='same'))(x) # Downsample to 32x32
    x = layers.TimeDistributed(layers.LeakyReLU(0.2))(x)

    # Encode Temporal History
    x = ConvGRU(filters=128, kernel_size=(3,3), return_sequences=True)(x)
    x = layers.BatchNormalization()(x)

    # Bottleneck ConvGRU (Summarize history into one state)
    # Output Shape: (Batch, 32, 32, 256)
    encoded_state = ConvGRU(filters=256, kernel_size=(3,3), return_sequences=False)(x)

    # --- ATTENTION BLOCK ---
    # We apply attention to the encoded summary before generating the future
    # This refines the spatial understanding of the last known state
    encoded_state = MultiHeadSpatiotemporalAttention(channels=256, num_heads=8)(encoded_state)
    encoded_state = layers.BatchNormalization()(encoded_state)

    # --- DECODER ---
    # Reshape to add time dimension: (Batch, 1, 32, 32, 256)
    x = layers.Reshape((1, img_size//2, img_size//2, 256))(encoded_state)

    # Repeat for OUTPUT_FRAMES: (Batch, 5, 32, 32, 256)
    x = layers.Lambda(lambda t: tf.tile(t, [1, OUTPUT_FRAMES, 1, 1, 1]))(x)

    # Predict future dynamics
    x = ConvGRU(filters=256, kernel_size=(3,3), return_sequences=True)(x)
    x = layers.BatchNormalization()(x)

    # Upsample Spatially
    x = layers.TimeDistributed(layers.Conv2DTranspose(128, (3, 3), strides=2, padding='same'))(x) # 32 -> 64
    x = layers.TimeDistributed(layers.LeakyReLU(0.2))(x)

    x = layers.TimeDistributed(layers.Conv2DTranspose(64, (3, 3), strides=1, padding='same'))(x)
    x = layers.TimeDistributed(layers.LeakyReLU(0.2))(x)

    outputs = layers.TimeDistributed(layers.Conv2D(1, (3, 3), padding='same', activation='sigmoid'))(x)

    return models.Model(input_layer, outputs, name="Generator")

def build_discriminator(output_frames, img_size):
    input_layer = Input(shape=(output_frames, img_size, img_size, 1))

    x = layers.TimeDistributed(layers.Conv2D(64, (3,3), strides=2, padding='same'))(input_layer)
    x = layers.TimeDistributed(layers.LeakyReLU(0.2))(x)
    x = layers.Flatten()(x)

    x = layers.Dense(512)(x)
    x = layers.LeakyReLU(0.2)(x)
    x = layers.Dropout(0.3)(x)
    output = layers.Dense(1, activation='sigmoid')(x)
    return models.Model(input_layer, output, name="Discriminator")

